"""Generate LaTeX numbers and compact tables from actual executed experiments."""

from pathlib import Path


def tex_number(number, digits=3):
    if number == 0:
        return "0"
    if abs(number) < 0.001 or abs(number) >= 1e6:
        mantissa, exponent = f"{number:.{digits}e}".split("e")
        return rf"{mantissa}\times 10^{{{int(exponent)}}}"
    return f"{number:.{digits}f}"


def write_report_results(root: Path, summary: dict):
    target = root / "report" / "sections" / "value_policy_results.tex"
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by scripts/run_value_policy.py; do not edit numerical results by hand."]

    def macro(name, value):
        lines.append("\\newcommand{\\" + name + "}{" + str(value) + "}")

    def table(name, columns, header, rows):
        text = [r"\begin{tabular}{" + columns + "}", r"\toprule", header + r" \\", r"\midrule"]
        text.extend(" & ".join(row) + r" \\" for row in rows)
        text.extend([r"\bottomrule", r"\end{tabular}"])
        macro(name, "\n" + "\n".join(text) + "\n")

    c = summary["comparison"]
    horizon = summary["horizon_validation"][-1]
    for name, value in {
        "VIIterations": summary["value_iteration"]["iterations"],
        "PIIterations": summary["policy_iteration"]["iterations"],
        "VIResidual": tex_number(c["vi_independent_residual"]),
        "PIResidual": tex_number(c["pi_independent_residual"]),
        "FixedResidual": tex_number(c["fixed_policy_residual"]),
        "MaxDifference": tex_number(c["max_value_difference"]),
        "MeanDifference": tex_number(c["mean_value_difference"]),
        "HorizonError": tex_number(horizon["sup_error"]),
        "HorizonBound": tex_number(horizon["tail_bound"]),
        "MinGap": tex_number(c["minimum_absolute_action_gap"]),
        "SmallVIError": tex_number(summary["exhaustive"]["vi_max_error"]),
        "MCEpisodes": f"{summary['metadata']['episodes']:,}",
        "MCHorizon": summary["metadata"]["simulation_horizon"],
        "MCCoverage": summary["monte_carlo"]["individual_ci_coverage_count"],
        "MCComparisons": summary["monte_carlo"]["comparisons"],
        "MCNondegenerate": summary["monte_carlo"]["nondegenerate_comparisons"],
        "MCNondegenerateCoverage": summary["monte_carlo"]["nondegenerate_ci_coverage_count"],
        "MCDeterministic": summary["monte_carlo"]["deterministic_cases"],
        "FamilyZ": f"{summary['monte_carlo']['familywise_z']:.3f}",
        "MaxTail": tex_number(max(r["raw_tail_bound"] for r in summary["monte_carlo"]["rows"])),
        "ValidationPasses": sum(summary["checks"].values()),
        "ValidationChecks": len(summary["checks"]),
        "ValueZero": f"{summary['policy_iteration']['value_at_0']:.6f}",
        "ValueMax": f"{summary['policy_iteration']['value_at_200']:.6f}",
    }.items():
        macro(name, value)
    table("SolverTable", "lrrr", r"Algorithm & Backups/passes & Residual & Runtime (s)", [
        [label, str(summary[key]["iterations"]), "$" + tex_number(summary[key]["bellman_residual"]) + "$",
         f"{summary[key]['runtime_seconds']:.4f}"]
        for label, key in (("Value iteration", "value_iteration"), ("Policy iteration", "policy_iteration"))])
    table("HorizonTable", "rrr", r"$T$ & Observed sup error & Discounted-tail bound", [
        [str(row["horizon"]), "$" + tex_number(row["sup_error"]) + "$", "$" + tex_number(row["tail_bound"]) + "$"]
        for row in summary["horizon_validation"]])
    labels = {"baseline": "Baseline", "zero_dispatch": "Free dispatch", "zero_holding": "Zero holding",
              "high_dispatch": "High dispatch", "high_holding": "High holding"}
    table("CostTable", "lrrrrr", r"Scenario & $c_f$ & $c_h$ & Threshold & $V^*(0)$ & $V^*(200)$", [
        [labels[row["scenario"]], f"{row['dispatch_cost']:g}", f"{row['holding_cost']:g}",
         "Never" if row["threshold"] is None else str(row["threshold"]),
         f"{row['value_at_0']:.2f}", f"{row['value_at_200']:.2f}"]
        for row in summary["parameter_experiments"]["cost"]])
    table("DiscountTable", "rrrrr", r"$\gamma$ & VI backups & Threshold & $V^*(0)$ & $V^*(200)$", [
        [f"{row['gamma']:.2f}", str(row["vi_iterations"]),
         "Never" if row["threshold"] is None else str(row["threshold"]),
         f"{row['value_at_0']:.2f}", f"{row['value_at_200']:.2f}"]
        for row in summary["parameter_experiments"]["discount"]])
    table("DeterministicTable", "rrrr", r"Arrivals & Threshold & $V^*(0)$ & $V^*(200)$", [
        [row["scenario"], str(row["threshold"]), f"{row['value_at_0']:.2f}", f"{row['value_at_200']:.2f}"]
        for row in summary["parameter_experiments"]["deterministic"]])
    table("TrajectoryTable", "rrrrrrr", r"$t$ & $s_t$ & $a_t$ & Cost & Arrivals & $s_{t+1}$ & $V^*(s_t)$", [
        [str(row[key]) for key in ("time", "state", "action", "immediate_cost", "arrivals", "next_state")]
        + [f"{row['current_state_value']:.3f}"] for row in summary["parameter_experiments"]["trajectory"]])
    table("MonteCarloTable", "lrrrr", r"Policy & $s_0$ & Exact & MC mean & 95\% CI", [
        [row["policy"].replace("_", r"\_"), str(row["initial_state"]), f"{row['exact_value']:.2f}",
         f"{row['mean']:.2f}", f"[{row['ci95_low']:.2f}, {row['ci95_high']:.2f}]"]
        for row in summary["monte_carlo"]["rows"] if row["initial_state"] == 0 or row["policy"] == "optimal"])
    table("ToleranceTable", "rrr", r"VI tolerance & Backups & Sup error against PI", [
        ["$" + tex_number(row["tolerance"]) + "$", str(row["iterations"]),
         "$" + tex_number(row["max_error_vs_pi"]) + "$"] for row in summary["tolerance_sensitivity"]])
    target.write_text("\n\n".join(lines) + "\n", encoding="utf-8")
